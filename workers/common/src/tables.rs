/// 표 찾기 (`Table[key]`, 없으면 undefined)
pub fn lookup(table: &[(&str, &str)], key: &crate::jsv::V) -> crate::jsv::V {
    let k = key.to_key();
    table.iter().rev().find(|(x, _)| *x == k).map_or(crate::jsv::V::Undef, |(_, v)| crate::jsv::V::from(*v))
}

